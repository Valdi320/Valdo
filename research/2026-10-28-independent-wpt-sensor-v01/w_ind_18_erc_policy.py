"""W-IND-18: make real KiCad ERC violations a BLOCKING PR status.

ERC zero is not hardware qualification. No circuit may be built or energized here.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import sys

from w_ind_17_erc_gate import evaluate

FLAGS = (
    "hardware_approved", "autonomous_fod_proven", "thermal_trip_proven",
    "overcurrent_proven", "reverse_blocking_proven", "independent_cuts_proven",
    "lithium_charging_approved",
)
KEYS = ("status", "erc_rc", "erc_count", "by_type", "by_severity", "erc_executed") + FLAGS

def check_evidence(report, attestation, source_bytes, source_path, ci_sha=None):
    """Return (ERC zero, count) or raise on inconsistent/forged/stale evidence."""
    if not isinstance(attestation, dict) or not isinstance(report, dict):
        raise ValueError("invalid evidence structure")
    rc = attestation.get("erc_rc")
    if type(rc) is not int:
        raise ValueError("ERC return code missing or invalid")
    actual = evaluate(rc, report)
    for key in KEYS:
        if attestation.get(key) != actual[key]:
            raise ValueError(f"ERC attestation mismatch: {key}")
    if attestation.get("source_sha256") != hashlib.sha256(source_bytes).hexdigest():
        raise ValueError("stale or altered schematic")
    if attestation.get("source_schematic") != source_path:
        raise ValueError("schematic path mismatch")
    if report.get("source") != Path(source_path).name:
        raise ValueError("KiCad report references different schematic")
    if attestation.get("kicad_version") != report.get("kicad_version") or report.get("kicad_version") != "9.0.2":
        raise ValueError("unqualified KiCad tool version")
    if attestation.get("test_kind") != "real_KiCad_ERC_ephemeral_CI":
        raise ValueError("ERC was not generated by required test path")
    if attestation.get("hardware_energized") is not False or attestation.get("physical_tests") != 0:
        raise ValueError("unexpected physical-test claims")
    if ci_sha is not None and attestation.get("github_sha") != ci_sha:
        raise ValueError("attestation belongs to another revision")
    return actual["erc_count"] == 0, actual["erc_count"]

def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--erc", type=Path, required=True)
    parser.add_argument("--attestation", type=Path, required=True)
    parser.add_argument("--schematic", type=Path, required=True)
    args = parser.parse_args(argv)
    try:
        report = json.loads(args.erc.read_text(encoding="utf-8"))
        attestation = json.loads(args.attestation.read_text(encoding="utf-8"))
        ok, n = check_evidence(report, attestation, args.schematic.read_bytes(),
                               args.schematic.as_posix(), os.getenv("GITHUB_SHA"))
    except (OSError, ValueError, TypeError, KeyError) as exc:
        print(f"::error title=Untrusted KiCad ERC evidence::{exc}")
        return 2
    if not ok:
        print(f"::error title=KiCad ERC has {n} unresolved violations::"
              "The circuit is NOT electrically reviewable. Evidence remains archived.")
        return 1
    print("::warning title=KiCad ERC zero is not hardware safety approval::"
          "FOD, independent cutoff, reverse blocking, temperature, and current remain unproven.")
    return 0

if __name__ == "__main__":
    sys.exit(main())
